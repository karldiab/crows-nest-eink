import { describe, it, expect } from 'vitest';
import { execFileSync, spawnSync } from 'node:child_process';
import { mkdtempSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { sanitizeIdentifier, makeIdentifiers, nameFromFile, generateHeader, type HeaderItem } from '../src/export/header';
import { IMAGE_BYTES, setPanelSize } from '../src/types';

// These tests were written for the Heltec 250 x 122 panel.
setPanelSize(250, 122);

describe('identifiers', () => {
  it('sanitises names', () => {
    expect(sanitizeIdentifier(nameFromFile('My Photo (1).JPG'))).toBe('egg_my_photo_1');
    expect(sanitizeIdentifier('My Photo (1)')).toBe('egg_my_photo_1');
    expect(sanitizeIdentifier('!!!')).toBe('egg_img');
  });
  it('de-duplicates', () => {
    expect(makeIdentifiers(['cat', 'cat', 'Cat!'])).toEqual(['egg_cat', 'egg_cat_2', 'egg_cat_3']);
  });
});

function items(n: number): HeaderItem[] {
  return Array.from({ length: n }, (_, i) => ({
    name: i === 2 ? 'quote "and" back\\slash' : `img ${i}`,
    fileName: `img-${i}.jpg`,
    description: 'dither, floyd-steinberg',
    bytes: new Uint8Array(IMAGE_BYTES).map((_, j) => (j * (i + 1)) & 0xff),
  }));
}

describe('header', () => {
  it('has the documented shape', () => {
    const h = generateHeader(items(3));
    expect(h.startsWith('// Auto-generated by Egg Studio. Do not edit by hand.\n')).toBe(true);
    expect(h).toContain('// 3 image(s), 250x122, 1-bit, 3904 bytes each, 11712 bytes total.');
    expect(h).toContain('#define EGG_WIDTH  250\n#define EGG_HEIGHT 122');
    expect(h).toContain('// img-0.jpg  (dither, floyd-steinberg)\nstatic const uint8_t egg_img_0[] PROGMEM = {\n  0x00, 0x01,');
    expect(h).toContain('"quote \\"and\\" back\\\\slash"');
    expect(h).toContain('static const uint16_t EGG_COUNT = 3;');
    // 16 bytes per line
    const line = h.split('\n').find((l) => l.startsWith('  0x'))!;
    expect(line.split(',').filter((s) => s.trim()).length).toBe(16);
  });

  it('rejects wrong-sized arrays', () => {
    const bad = items(1);
    bad[0].bytes = new Uint8Array(10);
    expect(() => generateHeader(bad)).toThrow();
  });

  // native g++/clang++, or g++ inside WSL on Windows
  const native = ['g++', 'clang++'].find((c) => spawnSync(c, ['--version']).status === 0);
  const wsl = !native && process.platform === 'win32' && spawnSync('wsl', ['-e', 'g++', '--version']).status === 0;
  it.skipIf(!native && !wsl)('compiles with g++ -Wall and has correct sizes', () => {
    const dir = mkdtempSync(join(tmpdir(), 'egg-'));
    const h = generateHeader(items(3)).replace('#include <Arduino.h>', '#include <stdint.h>\n#define PROGMEM');
    writeFileSync(join(dir, 'easter_eggs.h'), h);
    writeFileSync(
      join(dir, 'main.cpp'),
      `#include "easter_eggs.h"
#include <cstdio>
static_assert(sizeof(egg_img_0) == 3904, "size");
static_assert(sizeof(egg_img_1) == 3904, "size");
static_assert(sizeof(egg_quote_and_back_slash) == 3904, "size");
int main() { std::printf("%d %d %d\\n", (int)EGG_COUNT, EGG_WIDTH, EGG_HEIGHT); (void)EGGS; (void)EGG_NAMES; return EGG_COUNT == 3 ? 0 : 1; }
`,
    );
    let output: string;
    if (native) {
      const exe = join(dir, 'a.out');
      execFileSync(native, ['-Wall', '-Werror', '-o', exe, join(dir, 'main.cpp')], { stdio: 'pipe' });
      output = execFileSync(exe).toString();
    } else {
      const wdir = execFileSync('wsl', ['-e', 'wslpath', '-a', dir.replace(/\\/g, '/')]).toString().trim();
      output = execFileSync('wsl', ['-e', 'sh', '-c', `cd '${wdir}' && g++ -Wall -Werror -o /tmp/egg_test main.cpp && /tmp/egg_test`], {
        stdio: 'pipe',
      }).toString();
    }
    expect(output.trim()).toBe('3 250 122');
  });
});
