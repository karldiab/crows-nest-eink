import { IMAGE_BYTES, OUT_W, OUT_H } from '../types';

export interface HeaderItem {
  name: string;
  fileName: string;
  /** e.g. "dither, floyd-steinberg" */
  description: string;
  bytes: Uint8Array;
}

export function sanitizeIdentifier(name: string): string {
  const s = name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '_')
    .replace(/^_+|_+$/g, '');
  return s ? `egg_${s}` : 'egg_img';
}

/** Sanitised, de-duplicated identifiers in list order. */
export function makeIdentifiers(names: string[]): string[] {
  const used = new Set<string>();
  return names.map((n) => {
    const base = sanitizeIdentifier(n);
    let id = base;
    for (let i = 2; used.has(id); i++) id = `${base}_${i}`;
    used.add(id);
    return id;
  });
}

export function escapeCString(s: string): string {
  return s.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\r?\n/g, ' ');
}

function safeComment(s: string): string {
  return s.replace(/[\r\n]+/g, ' ').replace(/\*\//g, '*_/');
}

export function formatBytes(bytes: Uint8Array, indent = '  '): string {
  const lines: string[] = [];
  for (let i = 0; i < bytes.length; i += 16) {
    const chunk = Array.from(bytes.subarray(i, i + 16), (b) => '0x' + b.toString(16).padStart(2, '0'));
    lines.push(indent + chunk.join(', ') + (i + 16 < bytes.length ? ',' : ''));
  }
  return lines.join('\n');
}

export function formatArray(identifier: string, item: HeaderItem): string {
  return (
    `// ${safeComment(item.fileName)}  (${safeComment(item.description)})\n` +
    `static const uint8_t ${identifier}[] PROGMEM = {\n${formatBytes(item.bytes)}\n};\n`
  );
}

export function validateItems(items: HeaderItem[]): string[] {
  const errors: string[] = [];
  items.forEach((it, i) => {
    if (it.bytes.length !== IMAGE_BYTES)
      errors.push(`Image ${i + 1} (${it.name}) is ${it.bytes.length} bytes, expected ${IMAGE_BYTES}.`);
  });
  const ids = makeIdentifiers(items.map((i) => i.name));
  if (new Set(ids).size !== ids.length) errors.push('Identifiers are not unique.');
  return errors;
}

export function generateHeader(items: HeaderItem[], panelName?: string): string {
  const errors = validateItems(items);
  if (errors.length) throw new Error(errors.join('\n'));
  const ids = makeIdentifiers(items.map((i) => i.name));
  const n = items.length;
  const parts: string[] = [];
  parts.push(
    `// Auto-generated by Egg Studio. Do not edit by hand.\n` +
      `// ${n} image(s), ${OUT_W}x${OUT_H}, 1-bit, ${IMAGE_BYTES} bytes each, ${n * IMAGE_BYTES} bytes total.\n` +
      (panelName ? `// Panel: ${safeComment(panelName)}\n` : '') +
      `// Format: Adafruit GFX drawBitmap (MSB first, rows padded to bytes, 1 = black).\n` +
      `#pragma once\n#include <Arduino.h>\n\n` +
      `#define EGG_WIDTH  ${OUT_W}\n#define EGG_HEIGHT ${OUT_H}\n`,
  );
  items.forEach((it, i) => parts.push(formatArray(ids[i], it)));
  parts.push(`static const uint8_t* const EGGS[] = {\n${ids.map((id) => `  ${id},`).join('\n')}\n};\n`);
  parts.push(
    `static const char* const EGG_NAMES[] = {\n${items.map((it) => `  "${escapeCString(it.name)}",`).join('\n')}\n};\n`,
  );
  parts.push(`static const uint16_t EGG_COUNT = ${n};\n`);
  return parts.join('\n');
}

/** Default image name: the file name without its extension. */
export function nameFromFile(fileName: string): string {
  const base = fileName.split(/[\\/]/).pop() ?? fileName;
  const i = base.lastIndexOf('.');
  return i > 0 ? base.slice(0, i) : base;
}
